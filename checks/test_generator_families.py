RNG = np.random.default_rng(4944)
Y = np.ones(5) / np.sqrt(5)                       # the fine ground of the five-site path


def random_complex(*shape):
    return RNG.normal(size=shape) + 1j * RNG.normal(size=shape)


def unit(vector):
    return vector / np.linalg.norm(vector)


def projection(vector):
    return np.outer(vector, vector.conj())


def span_projection(vectors, tol=1e-10):
    left, singular, _ = np.linalg.svd(vectors, full_matrices=False)
    basis = left[:, singular > tol]
    return basis @ dag(basis)


def star_algebra_basis(generators, tol=1e-10):
    """A basis of the unital *-algebra generated by the generators (finite dimensions)."""
    n = generators[0].shape[0]
    pool = [np.eye(n, dtype=complex)] + [np.asarray(G, complex) for G in generators] \
        + [dag(np.asarray(G, complex)) for G in generators]
    basis = []

    def add(M):
        vectors = np.column_stack([B.reshape(-1) for B in basis] + [M.reshape(-1)])
        if rank(vectors, tol) > len(basis):
            basis.append(M)
            return True
        return False

    for M in pool:
        add(M)
    grew = True
    while grew:
        grew = False
        for A in list(basis):
            for B in list(basis):
                if add(A @ B):
                    grew = True
    return basis


def word_algebra_basis(generators, tol=1e-10):
    """A basis of the unital algebra of words in the generators, without adjoints."""
    n = generators[0].shape[0]
    basis = [np.eye(n, dtype=complex)]
    frontier = list(basis)
    while frontier:
        new = []
        for W in frontier:
            for G in generators:
                M = G @ W
                vectors = np.column_stack([B.reshape(-1) for B in basis] + [M.reshape(-1)])
                if rank(vectors, tol) > len(basis):
                    basis.append(M)
                    new.append(M)
        frontier = new
    return basis


def generated(basis, y):
    return span_projection(np.column_stack([X @ y for X in basis]))


def path_hamiltonian(n=5):
    H = np.zeros((n, n))
    for k in range(n - 1):
        H[k, k] += 0.5
        H[k + 1, k + 1] += 0.5
        H[k, k + 1] -= 0.5
        H[k + 1, k] -= 0.5
    return H


def site(k, n=5):
    E = np.zeros((n, n))
    E[k, k] = 1
    return E


def test_generated_space_of_a_family_and_its_centered_part():
    first = [site(0)]
    middle = [site(1), site(2), site(3)]
    K_first = generated(star_algebra_basis(first), Y)
    K_middle = generated(star_algebra_basis(middle), Y)
    K_union = generated(star_algebra_basis(first + middle), Y)
    assert [rank(K_first), rank(K_middle), rank(K_union)] == [2, 4, 5]
    # the centered vectors span the generated space minus the ground line, cyclic or not
    for family in (first, middle, first + middle):
        basis = star_algebra_basis(family)
        K = generated(basis, Y)
        centered = np.column_stack([X @ Y - np.vdot(Y, X @ Y) * Y for X in basis])
        assert_allclose(span_projection(centered), K - projection(Y), atol=1e-10)
    H = path_hamiltonian()
    assert generated_algebra_dim([H]) == 5
    # Reflection fixes the middle site and the ground. At that site the orbit
    # fills exactly the even subspace. Each of the four other sites is cyclic for H.
    reflection = np.eye(5)[::-1]
    even_projection = (np.eye(5) + reflection) / 2
    for k in range(5):
        basis = star_algebra_basis([H, site(k)])
        orbit = generated(basis, Y)
        if k == 2:
            assert_allclose(H @ reflection, reflection @ H, atol=1e-12)
            assert_allclose(site(k) @ reflection, reflection @ site(k), atol=1e-12)
            assert len(basis) == 11
            assert_allclose(orbit, even_projection, atol=1e-10)
        else:
            assert len(basis) == 25
            assert_allclose(orbit, np.eye(5), atol=1e-10)


def test_order_of_two_generators_on_the_ground():
    # Pauli X and Z on C^2 with y = e_0: the two orders give opposite vectors, so the
    # commutator does not annihilate y, and yet both orders give the same ray.
    X = np.array([[0, 1], [1, 0]], complex)
    Z = np.diag([1.0, -1.0]).astype(complex)
    y = np.array([1, 0], complex)
    first, second = Z @ X @ y, X @ Z @ y
    assert_allclose(first - second, (Z @ X - X @ Z) @ y, atol=1e-12)
    assert np.linalg.norm(first - second) > 1
    assert_allclose(first, -second, atol=1e-12)
    assert_allclose(projection(unit(first)), projection(unit(second)), atol=1e-12)
    # If one order annihilates the ground, that order has no conditional ray.
    P0 = projection(y)
    assert_allclose(P0 @ X @ y, 0, atol=1e-12)
    assert_allclose(X @ P0 @ y, [0, 1], atol=1e-12)
    # With contractions, proportional nonzero outputs can have different
    # success probabilities while preparing the same conditional pure state.
    plus = unit(np.ones(2))
    K = np.outer(y, plus.conj())
    u, v = K @ P0 @ plus, P0 @ K @ plus
    assert_allclose([np.vdot(u, u), np.vdot(v, v)], [0.25, 1], atol=1e-12)
    assert_allclose(projection(unit(u)), projection(unit(v)), atol=1e-12)
    # Hadamard and Z in opposite orders prepare orthogonal states with the
    # same diagonal probabilities. A plus-state projection distinguishes them.
    hadamard = np.array([[1, 1], [1, -1]]) / np.sqrt(2)
    u, v = hadamard @ Z @ y, Z @ hadamard @ y
    assert_allclose(np.vdot(u, v), 0, atol=1e-12)
    assert_allclose(np.abs(u)**2, np.abs(v)**2, atol=1e-12)
    assert_allclose([abs(np.vdot(plus, u))**2, abs(np.vdot(plus, v))**2], [1, 0], atol=1e-12)
    # two generators whose orders give different rays
    A, B = random_complex(4, 4), random_complex(4, 4)
    y = unit(random_complex(4))
    u, v = unit(B @ A @ y), unit(A @ B @ y)
    assert abs(abs(np.vdot(u, v)) - 1) > 1e-3
    # commuting generators give the same vector
    C = np.diag(random_complex(4))
    D = np.diag(random_complex(4))
    assert_allclose(D @ C @ y, C @ D @ y, atol=1e-12)
    # different rays can still agree on a chosen algebra: e_1 and e_2 on C^3 with the
    # algebra generated by the projection onto e_0
    e = np.eye(3)
    algebra = star_algebra_basis([projection(e[0])])
    for M in algebra:
        assert_allclose(np.vdot(e[1], M @ e[1]), np.vdot(e[2], M @ e[2]), atol=1e-12)


def test_content_equivalence_and_moves_within_a_class():
    # On the five-site path, xi and eta agree on the site algebra and differ on Pi_D.
    xi = np.array([0, 1, 1, 1, 1]) / 2
    eta = np.array([0, 1, 1, -1, -1]) / 2
    sites = [site(k) for k in range(5)]
    for M in sites:
        assert_allclose(np.vdot(xi, M @ xi), np.vdot(eta, M @ eta), atol=1e-12)
    A = np.array([[1, 0], [0, 1], [0, 1], [0, 1], [0, 1]]) / 2
    P_D = span_projection(A)
    assert_allclose([np.vdot(xi, P_D @ xi).real, np.vdot(eta, P_D @ eta).real], [1, 0], atol=1e-12)
    # a unitary in the site algebra carries xi to eta
    U = np.diag([1, 1, 1, -1, -1]).astype(complex)
    assert_allclose(U @ xi, eta, atol=1e-12)
    # A unitary preserves the restriction of every state to an algebra exactly when it
    # commutes with that algebra.
    for _ in range(3):
        rho = (lambda M: M @ dag(M))(random_complex(5, 5))
        rho /= np.trace(rho).real
        moved = U @ rho @ dag(U)
        for M in sites:
            assert_allclose(np.trace(moved @ M), np.trace(rho @ M), atol=1e-12)
    W = expm(-1j * path_hamiltonian())                         # does not commute with the sites
    assert np.linalg.norm(W @ site(0) - site(0) @ W) > 0.1
    rho = projection(np.eye(5)[0])
    changed = max(abs(np.trace(W @ rho @ dag(W) @ M) - np.trace(rho @ M)) for M in sites)
    assert changed > 0.1
    # Equal expectations of the effects of an algebra give equal restrictions: in finite
    # dimensions every element is a combination of four effects.
    M = random_complex(5, 5)
    M = np.diag(np.diag(M))                                     # an element of the site algebra
    parts = []
    for herm in ((M + dag(M)) / 2, (M - dag(M)) / 2j):
        values, vectors = np.linalg.eigh(herm)
        scale = np.max(np.abs(values)) + 1e-12
        positive = vectors @ np.diag(np.clip(values, 0, None)) @ dag(vectors) / scale
        negative = vectors @ np.diag(np.clip(-values, 0, None)) @ dag(vectors) / scale
        for E in (positive, negative):
            ev = np.linalg.eigvalsh(E)
            assert ev.min() > -1e-12 and ev.max() < 1 + 1e-12
        parts.append((scale, positive, negative))
    (s1, p1, n1), (s2, p2, n2) = parts
    assert_allclose(s1 * (p1 - n1) + 1j * s2 * (p2 - n2), M, atol=1e-10)


def test_a_family_that_keeps_the_ground():
    H = path_hamiltonian()
    assert_allclose(H @ Y, 0, atol=1e-12)
    basis = star_algebra_basis([H])
    assert len(basis) == 5
    # every element acts on y by the scalar omega(X), which is multiplicative
    omega = lambda X: np.vdot(Y, X @ Y)
    for X in basis:
        assert_allclose(X @ Y, omega(X) * Y, atol=1e-10)
        assert_allclose(X @ projection(Y), projection(Y) @ X, atol=1e-10)
    for _ in range(5):
        c1, c2 = random_complex(5), random_complex(5)
        X1, X2 = sum(c * B for c, B in zip(c1, basis)), sum(c * B for c, B in zip(c2, basis))
        assert_allclose(omega(X1 @ X2), omega(X1) * omega(X2), atol=1e-10)
        assert_allclose(omega(dag(X1)), np.conj(omega(X1)), atol=1e-10)
        centered = X1 - omega(X1) * np.eye(5)
        assert_allclose(centered @ Y, 0, atol=1e-10)
    assert rank(generated(basis, Y)) == 1
    # The vector state on this algebra is a character, hence pure, and not faithful:
    # the spectral projections of H at its other eigenvalues annihilate y.
    values, vectors = np.linalg.eigh(H)
    for k in range(1, 5):
        Pk = projection(vectors[:, k])
        assert_allclose(Pk @ Y, 0, atol=1e-10)
        assert np.linalg.norm(Pk) > 0.5
    # the site algebra stays cyclic: the condition concerns the family only
    assert rank(generated(star_algebra_basis([site(k) for k in range(5)]), Y)) == 5

    # One-sided: |y><w| keeps the line, its adjoint does not. Words without adjoints keep
    # the line; the *-algebra generated by the same operator does not.
    w = unit(random_complex(5))
    w = unit(w - np.vdot(Y, w) * Y)
    G = np.outer(Y, w.conj())
    assert_allclose(G @ Y, 0, atol=1e-12)
    for X in word_algebra_basis([G]):
        assert_allclose(X @ Y - np.vdot(Y, X @ Y) * Y, 0, atol=1e-12)
    assert rank(generated(star_algebra_basis([G]), Y)) == 2
