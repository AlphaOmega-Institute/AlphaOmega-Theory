"""Small linear-algebra utilities used by several checks."""
import numpy as np
from scipy.linalg import orth


def rank(M, tol=1e-10):
    return int(np.linalg.matrix_rank(M, tol=tol))


def eigenspace(op, value, atol=1e-9):
    """Orthonormal basis (columns) of the eigenspace of a Hermitian matrix."""
    w, V = np.linalg.eigh(op)
    return V[:, np.isclose(w, value, atol=atol, rtol=0.0)]


SPECTRAL_TOLERANCE = 1e-9


def spectral_blocks(H, tol=SPECTRAL_TOLERANCE):
    """List of (eigenvalue, orthonormal eigenbasis) for a Hermitian matrix.

    Eigenvalues are grouped greedily from the lowest: a group starts at the lowest
    eigenvalue not yet assigned and takes every eigenvalue within ``tol`` of that start.
    Consequently

    * every eigenvector belongs to exactly one block, so the blocks are disjoint and
      exhaustive and the spectral weights sum to Gamma^* Gamma;
    * no block spans more than ``tol``, so neighbours cannot chain into a wide group;
    * the grouping does not depend on where eigenvalues fall relative to a decimal grid.

    ``tol`` is an absolute tolerance in the units of H.  Energies closer than ``tol`` are
    treated as one level.  For genuinely distinct energies that is a numerical
    approximation to the exact response, which a smaller ``tol`` resolves.  The reported
    eigenvalue is the mean of the group.
    """
    w, V = np.linalg.eigh(H)
    blocks, start = [], 0
    for k in range(1, len(w) + 1):
        if k == len(w) or w[k] - w[start] > tol:
            blocks.append((float(np.mean(w[start:k])), V[:, start:k]))
            start = k
    return blocks


def response_weights(H, Gamma):
    """Spectral weights R_lam = Gamma^* E_lam Gamma of the port response
    Gamma^* (H - z)^{-1} Gamma = sum_lam R_lam / (lam - z)."""
    out = []
    for lam, E in spectral_blocks(H):
        EG = E.conj().T @ Gamma
        out.append((lam, EG.conj().T @ EG))
    return out


def minimal_space(H, Gamma, tol=1e-10):
    """Orthonormal basis of the response-generated subspace: the smallest
    reducing subspace of H containing the range of Gamma."""
    pieces = [E @ (E.conj().T @ Gamma) for _, E in spectral_blocks(H)]
    return orth(np.hstack(pieces), rcond=tol)


def generated_algebra_dim(generators, tol=1e-9):
    """Dimension of the unital algebra generated by the given square matrices."""
    n = generators[0].shape[0]
    basis = [np.eye(n, dtype=complex)]

    def add(M):
        trial = np.array([x.ravel() for x in basis + [M]])
        if np.linalg.matrix_rank(trial, tol=tol) > len(basis):
            basis.append(M)
            return True
        return False

    for g in generators:
        add(g.astype(complex))
    grew = True
    while grew:
        grew = False
        for x in list(basis):
            for y in list(basis):
                if add(x @ y):
                    grew = True
    return len(basis)


def in_span(vec, basis_cols, atol=1e-10):
    """True when vec lies in the column span of an orthonormal basis."""
    return np.linalg.norm(vec - basis_cols @ (basis_cols.conj().T @ vec)) < atol
